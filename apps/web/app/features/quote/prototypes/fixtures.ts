/** La gama alta con dos alternativas guardadas en el slot de la tarjeta de video. */
export const withAlternatives: QuoteDetail = (() => {
  const gpu = highEnd.items.find((i) => i.slot === "gpu");
  if (!gpu?.offer) return highEnd;
  const alt = (id: number, name: string, delta: number) => ({
    ...gpu,
    id,
    isSelected: false,
    product: { ...gpu.product, id: gpu.product.id + id, name, slug: `${gpu.product.slug}-${id}` },
    offer: gpu.offer
      ? { ...gpu.offer, priceCash: gpu.offer.priceCash + delta, priceCard: gpu.offer.priceCard + delta }
      : null,
  });
  return {
    ...highEnd,
    items: [
      ...highEnd.items,
      alt(9001, "ASUS Prime RTX 5070 Ti 16GB OC", 45_000),
      alt(9002, "Gigabyte RTX 5070 Ti Eagle OC 16GB", -12_000),
    ],
  };
})();

/** Plan de condensar inventado sobre `highEnd`: de 4 tiendas a 2 pagando $17.910 más. */
export const condensePlan: QuoteCondensePlan = (() => {
  const priced = highEnd.items.filter((i) => i.offer);
  const stores = [
    { slug: "tecnomas", name: "Tecnomas" },
    { slug: "nuevatec", name: "Nuevatec" },
  ];
  const items = priced.map((i, n) => {
    const store = stores[n % 2] as (typeof stores)[number];
    const cheapest = i.offer as NonNullable<typeof i.offer>;
    const extra = n % 3 === 0 ? 5_970 : 0;
    return {
      itemId: i.id,
      listingId: cheapest.id,
      store,
      priceCash: cheapest.priceCash + extra,
      cheapestStore: { slug: cheapest.store.slug, name: cheapest.store.name },
      cheapestPriceCash: cheapest.priceCash,
    };
  });
  const extraCash = items.reduce((s, i) => s + i.priceCash - i.cheapestPriceCash, 0);
  return {
    improves: true,
    storesBefore: new Set(priced.map((i) => i.offer?.store.slug)).size,
    storesAfter: 2,
    extraCash,
    items,
    stores: stores.map((s) => {
      const own = items.filter((i) => i.store.slug === s.slug);
      return { ...s, itemIds: own.map((i) => i.itemId), subtotalCash: own.reduce((t, i) => t + i.priceCash, 0) };
    }),
  };
})();
